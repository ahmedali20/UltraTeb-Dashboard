create table if not exists public.bonus_items (
  id bigint generated by default as identity primary key,
  received_date date not null default current_date,
  supplier_name text,
  item_code text not null,
  product_name text not null,
  quantity numeric(14,3) not null check (quantity > 0),
  estimated_unit_cost numeric(14,4) not null default 0 check (estimated_unit_cost >= 0),
  reference_no text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists bonus_items_received_date_idx on public.bonus_items (received_date desc);
create index if not exists bonus_items_item_code_idx on public.bonus_items (item_code);

alter table public.bonus_items enable row level security;
grant all on table public.bonus_items to service_role;
grant usage, select on sequence public.bonus_items_id_seq to service_role;
