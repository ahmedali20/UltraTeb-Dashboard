create table if not exists public.invoice_collections (
  id bigint generated by default as identity primary key,
  invoice_id text not null,
  invoice_no text not null,
  customer_code text,
  customer_name text not null,
  collection_date date not null,
  amount numeric(14,2) not null check (amount > 0),
  payment_method text not null default 'BANK_TRANSFER'
    check (payment_method in ('CASH', 'BANK_TRANSFER', 'CHEQUE', 'OTHER')),
  cheque_status text,
  cheque_status_date date,
  reference_no text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists invoice_collections_invoice_id_idx
  on public.invoice_collections (invoice_id);
create index if not exists invoice_collections_invoice_no_idx
  on public.invoice_collections (invoice_no);
create index if not exists invoice_collections_customer_name_idx
  on public.invoice_collections (customer_name);
create index if not exists invoice_collections_collection_date_idx
  on public.invoice_collections (collection_date desc);

alter table public.invoice_collections enable row level security;

alter table public.invoice_collections
  add column if not exists transfer_fees numeric(14,2) not null default 0
  check (transfer_fees >= 0);

alter table public.invoice_collections
  add column if not exists cheque_status text,
  add column if not exists cheque_status_date date;

update public.invoice_collections
set cheque_status = 'IN_TREASURY',
    cheque_status_date = coalesce(cheque_status_date, collection_date)
where payment_method = 'CHEQUE' and cheque_status is null;

update public.invoice_collections
set cheque_status = null, cheque_status_date = null
where payment_method <> 'CHEQUE';

alter table public.invoice_collections
  drop constraint if exists invoice_collections_cheque_status_check;
alter table public.invoice_collections
  add constraint invoice_collections_cheque_status_check check (
    (payment_method = 'CHEQUE' and cheque_status in ('IN_TREASURY', 'UNDER_COLLECTION', 'COLLECTED', 'REFUSED', 'RETURNED_TO_CUSTOMER'))
    or (payment_method <> 'CHEQUE' and cheque_status is null)
  );

